def candidates_for_signal(signal: str) -> list[str]:
    """Return normalized match candidates for a signal id."""
    token = signal.strip()
    if not token:
        return []
    raw = {
        token,
        token.replace("_", " "),
        token.replace("_", "-"),
        *SIGNAL_SYNONYMS.get(token, ()),
    }
    # Drop ultra-short ambiguous tokens from auto-humanization only;
    # explicit lexicon entries are kept as authored.
    return [c.casefold().strip() for c in raw if c and c.strip()]
